// The biases to watch for, given the stages and methods a study uses. With methods picked, a bias counts when
// one of them is prone to it; with stages picked, only biases that threaten one of those stages count.
export function biasesForStudy(stages, methods) {
  if (!stages.length && !methods.length) return [];
  return BIASES.filter((b) => (!stages.length || b.stages.some((s) => stages.includes(s)))
    && (!methods.length || (b.threatens || []).some((m) => methods.includes(m))));
}
