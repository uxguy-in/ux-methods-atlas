// Biases a method guards against, and biases it is especially prone to.
export function biasesForMethod(methodId) {
  return {
    guards: BIASES.filter((b) => b.methods.includes(methodId)),
    prone: BIASES.filter((b) => (b.threatens || []).includes(methodId)),
  };
}

// Biases a calculator helps with.
export const biasesForCalc = (calcId) => BIASES.filter((b) => b.calcs.includes(calcId));

