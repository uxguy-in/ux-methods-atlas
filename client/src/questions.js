export const THEME_BY_ID = new Map(THEMES.map((t) => [t.id, t]));
export const QUESTION_BY_ID = new Map(QUESTIONS.map((q) => [q.id, q]));
export const themeOf = (id) => THEME_BY_ID.get(id) || THEMES[0];

const norm = (s) => String(s || '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');

const startsWord = (hay, s) => new RegExp(`(^|[^a-z0-9])${s.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')}`).test(hay);

// Every word of the query must match the question (its text, answer, keywords, reframe or theme), either as typed
// or through one of its synonyms.
export function matchQuestion(q, query) {
  const words = norm(query).split(/\s+/).filter(Boolean);
  if (!words.length) return true;
  const hay = norm([q.question, q.answer, ...(q.keywords || []), q.askInstead?.question, themeOf(q.theme).name].join(' '));
  return words.every((w) => {
    if (startsWord(hay, w)) return true;
    return SYNONYMS.some((group) => group.includes(w) && group.some((s) => startsWord(hay, s)));
  });
}

// Questions that recommend this method, best first (where it sits earlier in the list), for method pages.
export function questionsForMethod(methodId, max = 2) {
  return QUESTIONS
    .map((q) => ({ q, i: q.methods.findIndex((x) => x.id === methodId) }))
    .filter((x) => x.i >= 0)
    .sort((a, b) => a.i - b.i)
    .slice(0, max)
    .map((x) => x.q);
}
