"""Builds client/src/questions-library.js from the questions-enrichment proposal (reviewed 2026-10-30).

Insights, further reading, rules of thumb and pitfalls are paraphrased from the book-mining notes; new questions are
appended to the library. Three proposed questions that overlap existing ones are folded into those instead.
"""
import json, sys
E = sys.argv[1] if len(sys.argv) > 1 else '/mnt/project-files/ux-methods-atlas/questions-enrichment'
enr = json.load(open(f'{E}/enrichment.json'))['enrichment']
new = json.load(open(f'{E}/new-questions.json'))['questions']
BOOKS = {b['id']: b for b in (lambda j: j if isinstance(j, list) else j['books'])(json.load(open('server/data/books.json')))}
MERGE = {'did-redesign-dip-recover': 'is-the-dip-real', 'time-to-adopt': 'is-feature-adopted', 'are-findings-credible': 'are-we-confirming'}

def src(s):
    if s.get('kind') == 'book':
        b = BOOKS.get(s.get('booksJsonId'))
        # A book listed in the atlas library takes its library title, so the link to the library finds it.
        return {k: v for k, v in {'title': b['title'] if b else s.get('title'), 'author': s.get('author'), 'year': s.get('year'), 'book': b and b['id']}.items() if v}
    return {'title': "The atlas editors' notes"}
def items(v, f):
    return [{'text': it['text'], 'source': src(it['source'])} for it in v.get(f, [])]
def reading(v):
    return [{**src({**r, 'kind': 'book'}), **({'why': r['why']} if r.get('why') else {})} for r in v.get('furtherReading', [])]

lib = {}
def add(qid, v):
    d = lib.setdefault(qid, {'insights': [], 'reading': [], 'rules': [], 'pitfalls': []})
    d['insights'] += items(v, 'fromTheLibrary'); d['rules'] += items(v, 'rulesOfThumb'); d['pitfalls'] += items(v, 'pitfalls')
    seen = {r['title'] for r in d['reading']}
    d['reading'] += [r for r in reading(v) if r['title'] not in seen]
for qid, v in enr.items(): add(qid, v)

more = []
for q in new:
    if q['id'] in MERGE: add(MERGE[q['id']], q); continue
    add(q['id'], q)
    out = {k: q[k] for k in ['id', 'question', 'theme', 'answer', 'stages', 'methods', 'calcs', 'biases'] if k in q}
    if q.get('askInstead'): out['askInstead'] = {'question': q['askInstead'], 'why': 'It turns the question into one your evidence can actually answer.'}
    if q.get('keywords'): out['keywords'] = q['keywords']
    more.append(out)
for d in lib.values():
    for k in [k for k, x in d.items() if not x]: del d[k]

head = ('// Generated by server/scripts/build-questions-library.py from the reviewed questions-enrichment proposal. Edit\n'
        '// the proposal and regenerate rather than editing by hand.\n'
        '//\n// LIBRARY: for each question id, insights, further reading, rules of thumb and pitfalls paraphrased from the\n'
        "// atlas's reading notes, each with its source (book id from server/data/books.json where matched).\n"
        '// MORE_QUESTIONS: questions drawn from the same notes, in the same shape as QUESTIONS in questions.js.\n\n')
open('client/src/questions-library.js', 'w').write(head + 'export const LIBRARY = ' + json.dumps(lib, indent=1, ensure_ascii=False) + ';\n\nexport const MORE_QUESTIONS = ' + json.dumps(more, indent=1, ensure_ascii=False) + ';\n')
print(len(lib), 'questions with library notes;', len(more), 'new questions')
